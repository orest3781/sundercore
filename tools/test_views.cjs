'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname,'../site/app.js'),'utf8');
const pure = source.slice(0,source.indexOf('function render('));
const context = {localStorage:{getItem:()=>null},document:{querySelector:()=>null}};
vm.runInNewContext(pure+'\nglobalThis.views={materialsHTML,activity,sessionSeconds,overview,campHTML,sourceHTML};',context);
const {materialsHTML,activity,sessionSeconds,overview,campHTML,sourceHTML}=context.views;
const capture='2026-11-15T12:00:00Z', end=Date.parse(capture)/1000;
const base={id:'fixture',exportedAt:capture,character:{name:'Test',level:22,xp:50,xpForNextLevel:100,moneyCopper:100},bags:{free:9,capacity:54},fieldPlan:{materials:[],spots:[],tasks:[]},goals:[],nextSteps:[],professions:[]};
function material(row){return materialsHTML({...base,fieldPlan:{materials:[{id:2592,name:'Wool Cloth',need:15,bag:1,missing:0,...row}]}},true);}
assert.match(material({bank:8,action:'Withdraw'}),/Withdraw 8/);
assert.doesNotMatch(material({bank:8,action:'Withdraw'}),/Withdraw 0/);
assert.match(material({bank:8,missing:6}),/Withdraw 8 · Acquire 6 more/);
assert.match(material({make:2,action:'Craft'}),/Craft 2/);
assert.doesNotMatch(material({make:2,action:'Craft'}),/Craft 0/);
assert.match(material({done:true}),/Goal ready/);
assert.match(material({collect:true,missing:5}),/Collect 5 more.*received this outing/);
assert.equal(sessionSeconds({seconds:600,elapsed:900},capture),600);
assert.equal(sessionSeconds({started:end-2000,elapsed:300,pausedAt:end-1000},capture),300,'paused elapsed excludes paused wall time');
assert.equal(sessionSeconds({started:end-2000,elapsed:300,segmentAt:end-200},capture),500,'running segment freezes at snapshot');
assert.equal(sessionSeconds({},capture),null,'unknown duration stays unknown');
assert.equal(sessionSeconds({elapsed:0,pausedAt:end},capture),0,'known zero remains zero');
const active={label:'Current camp',started:end-200,segmentAt:end-200,elapsed:0,xp:0,kills:0,receivedLoot:{}};
let html=activity({...base,activeSession:active,sessions:[]});
assert.match(html,/Current camp/);assert.match(html,/SAVED IN PROGRESS/);assert.match(html,/3m 20s/);
assert.match(html,/Items received<\/small><strong>0<\/strong>/,'empty confirmed receipt map is measured zero');
html=activity({...base,sessions:[{label:'Legacy',started:end-200,seconds:200,xp:0,kills:0}]});
assert.match(html,/Items received<\/small><strong>—<\/strong>/,'absent receipt data stays unknown');
assert.match(html,/XP per session hour/);assert.match(html,/quest rewards and rested XP/);assert.match(html,/Travel and idle time/);
assert.match(activity({...base,coverage:{sessions:'Not exported by this addon version'}}),/Outings were not exported/);
assert.match(activity({...base,coverage:{sessions:'Snapshot session summaries'},sessions:[]}),/first outing starts in game/);
html=activity({...base,sessions:[{label:'Earlier',started:10,seconds:10},{label:'Later',started:20,seconds:10}]});
assert.ok(html.indexOf('Later')<html.indexOf('Earlier'),'newest outings first');
const goals=Array.from({length:9},(_,i)=>({id:'goal'+i,title:'Goal '+(i+1),priority:9-i,why:'Reason'}));
html=overview({...base,goals});assert.match(html,/Show 3 more goals/);assert.match(html,/Goal 9/);assert.match(html,/priority-number">07</);
html=campHTML({spot:{name:'Known camp',source:'Personal observations',zone:'Known zone',low:20,high:22},reasons:[]});
assert.match(html,/Personal observations/);assert.doesNotMatch(html,/Classic-derived camp/);
assert.doesNotThrow(()=>sourceHTML(undefined),'about dialog handles no loaded snapshot');
console.log('PASS: material action quantities, snapshot-frozen/paused sessions, unknown versus zero, active outings, newest ordering, all goals, and source labels');
